const uint8_t *ndfs_boot_blob(ndfs_boot_blob_id_t id, size_t *size)
{
    switch (id) {
        case NDFS_BOOT_BLOB_SMD:        if (size) *size = sizeof(blob_smd);        return blob_smd;
        case NDFS_BOOT_BLOB_WINCHESTER: if (size) *size = sizeof(blob_winchester); return blob_winchester;
        case NDFS_BOOT_BLOB_SCSI:       if (size) *size = sizeof(blob_scsi);       return blob_scsi;
        case NDFS_BOOT_BLOB_FLOPPY360:  if (size) *size = sizeof(blob_floppy360);  return blob_floppy360;
        case NDFS_BOOT_BLOB_FLOPPY616:  if (size) *size = sizeof(blob_floppy616);  return blob_floppy616;
        default:                        if (size) *size = 0;                       return NULL;
    }
}


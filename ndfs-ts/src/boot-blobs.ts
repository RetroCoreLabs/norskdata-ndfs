export type BootBlobName = 'smd' | 'winchester' | 'scsi' | 'floppy360' | 'floppy616';

/** The 2000 byte boot area for `name`. Returns a fresh copy. */
export function bootBlob(name: BootBlobName): Uint8Array {
  switch (name) {
    case 'smd': return decode(B64_SMD);
    case 'winchester': return decode(B64_WINCHESTER);
    case 'scsi': return decode(B64_SCSI);
    case 'floppy360': return decode(B64_FLOPPY360);
    case 'floppy616': return decode(B64_FLOPPY616);
  }
}

/** The last page (2048 bytes) of the real SCSI disk. Returns a fresh copy. */
export function scsiLastPage(): Uint8Array {
  return decode(B64_SCSI_LAST_PAGE);
}
